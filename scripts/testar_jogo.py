"""Teste do jogo no navegador (Playwright): fluxo completo na TV e no celular + relatório. Uso: testar_jogo.py PASTA_REPO PASTA_PRINTS [cidade]"""
import sys, time
from pathlib import Path
from playwright.sync_api import sync_playwright
RAIZ = Path(sys.argv[1]).resolve(); OUT = Path(sys.argv[2]); OUT.mkdir(exist_ok=True)
CIDADE = sys.argv[3] if len(sys.argv) > 3 else "Chapec"
url = RAIZ.joinpath("index.html").as_uri()
erros = []
with sync_playwright() as p:
    b = p.chromium.launch(args=["--autoplay-policy=no-user-gesture-required"])
    for nome, vp, toque in [("tv", {"width": 1920, "height": 1080}, False), ("cel", {"width": 390, "height": 844}, True)]:
        ctx = b.new_context(viewport=vp, has_touch=toque, is_mobile=toque, device_scale_factor=2 if toque else 1)
        pg = ctx.new_page()
        pg.on("console", lambda m: erros.append(f"{nome} console {m.type}: {m.text}") if m.type in ("error", "warning") else None)
        pg.on("pageerror", lambda e: erros.append(f"{nome} pageerror: {e}"))
        pg.goto(url); pg.wait_for_timeout(1800)
        pg.screenshot(path=str(OUT / f"{nome}_1_inicio.png"))
        if toque: pg.tap("#tela-inicio")
        else: pg.keyboard.press("Enter")
        pg.wait_for_timeout(300)
        pg.fill("#busca", CIDADE); pg.wait_for_timeout(200)
        pg.screenshot(path=str(OUT / f"{nome}_2_cidade.png"))
        pg.keyboard.press("Enter")
        pg.wait_for_timeout(1500)
        pg.screenshot(path=str(OUT / f"{nome}_3_contagem.png"))
        pg.wait_for_timeout(2300)
        t0 = time.time()
        for tecla in ["ArrowRight", "ArrowDown", "ArrowLeft", "ArrowUp", "ArrowRight"]:
            pg.keyboard.down(tecla); pg.keyboard.down("Space"); pg.wait_for_timeout(1300); pg.keyboard.up("Space"); pg.keyboard.up(tecla)
        pg.keyboard.down("ArrowDown"); pg.wait_for_timeout(600)
        pg.screenshot(path=str(OUT / f"{nome}_4_voo.png"))
        pg.keyboard.up("ArrowDown")
        print(nome, "estado", pg.evaluate("J.estado"), "cad", pg.evaluate("J.cadastrados"), "n", pg.evaluate("J.C.n"), "pts", pg.evaluate("Math.round(J.pontos)"), "tempo", pg.evaluate("J.tempo.toFixed(1)"))
        pg.evaluate("J.tempo = 0.05")
        pg.wait_for_timeout(3600)
        print(nome, "estado depois", pg.evaluate("J.estado"))
        pg.screenshot(path=str(OUT / f"{nome}_5_fim.png"), full_page=True)
        pg.click("[data-acao=ficha]"); pg.wait_for_timeout(300)
        pg.fill("#f-nome", "Prefeito Teste"); pg.fill("#f-whats", "49999719388"); pg.check("#f-consent")
        pg.click("#f-cargo button >> nth=0")
        pg.screenshot(path=str(OUT / f"{nome}_6_ficha.png"))
        pg.click("[data-acao=salvar-ficha]"); pg.wait_for_timeout(400)
        pg.screenshot(path=str(OUT / f"{nome}_7_ranking.png"))
        print(nome, "estado final", pg.evaluate("J.estado"), pg.evaluate("localStorage.getItem('voo-cadastral:partidas')")[:220])
        pg.keyboard.press("Control+e"); pg.wait_for_timeout(300)
        pg.screenshot(path=str(OUT / f"{nome}_8_equipe.png"))
        ctx.close()
    ctx = b.new_context(viewport={"width": 900, "height": 1300})
    pg = ctx.new_page()
    pg.on("pageerror", lambda e: erros.append(f"relatorio pageerror: {e}"))
    pg.goto(RAIZ.joinpath("relatorio.html").as_uri() + "?c=4204202&n=Prefeito%20Teste&cargo=Prefeito(a)"); pg.wait_for_timeout(1200)
    pg.screenshot(path=str(OUT / "relatorio.png"), full_page=True)
    pg.pdf(path=str(OUT / "relatorio.pdf"), format="A4", print_background=True)
    b.close()
print("\n".join(erros) or "sem erros no console")
